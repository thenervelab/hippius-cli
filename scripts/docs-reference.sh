#!/usr/bin/env bash
# Renders the help of hipc, and of every group and command under it, as one Markdown page.
#
# Usage: scripts/docs-reference.sh <path to hipc> > docs/commands.md
#
# The page is the help, word for word: a change to a command's help text is a change to the
# page, and the docs_reference test in crates/hippius-cli/tests/scripts fails until the
# committed page is regenerated from the built binary (TENETS.md, tenet 16). Nothing here is
# written by hand, so there is nothing to drift.
#
# The command tree is read from the help itself, the lines under `Commands:` of each group,
# so the script needs only bash, awk, and the binary; `hipc schema` is the machine-readable
# form of the same tree, and a test checks that every path it lists has a heading here.
# The global options are printed once, under `hipc`. Every other page ends with one line that
# points to them, which is cut here, since this page already lists them under `hipc`.
set -euo pipefail

die() {
  echo "docs-reference: error: $1" >&2
  exit 1
}

if [[ $# -ne 1 ]]; then
  echo "usage: $0 <path to hipc> > docs/commands.md" >&2
  exit 2
fi
HIPC="$1"
[[ -x "$HIPC" && -f "$HIPC" ]] || die "$HIPC is not an executable file"

# The help of one page. --help is text in every output mode and touches no file and no
# network, so the environment does not matter.
help_of() {
  "$HIPC" "$@" --help
}

# The names under `Commands:` in a help text, one per line; nothing for a leaf.
subcommands_in() {
  awk '
    /^Commands:$/ { listing = 1; next }
    listing && /^$/ { exit }
    listing { print $1 }
  ' <<<"$1"
}

# A help text without its last line, the pointer to the global options under `hipc`, and
# the blank line before it.
without_global_options() {
  local pointer='Global options: see hipc --help'
  printf '%s' "${1%$'\n\n'"$pointer"}"
}

# The GitHub anchor of a heading: the words lowercased and joined by hyphens. Command words
# are lowercase ASCII letters, digits, and hyphens (the tenet 2 grammar), which GitHub keeps
# as they are; tr covers the day a word is not.
anchor_of() {
  local words="$1"
  echo "${words// /-}" | tr '[:upper:]' '[:lower:]'
}

# One Markdown section: the heading, then the help in a text fence.
section() {
  local level="$1" title="$2" body="$3" fence='```'
  printf '%s %s\n\n%stext\n%s\n%s\n\n' "$level" "$title" "$fence" "$body" "$fence"
}

# Walks the tree under the path in "$@" and appends each page to TOC and BODY. Depth-first,
# in the order the help lists the commands, which is the order of the parser, so two runs
# on one binary print the same bytes.
TOC=''
BODY=''
walk() {
  local help title level
  help=$(help_of "$@")
  title="hipc $*"
  if [[ $# -eq 1 ]]; then
    level='##'
  else
    level='###'
  fi
  TOC+="- [\`$title\`](#$(anchor_of "$title"))"$'\n'
  BODY+=$(section "$level" "$title" "$(without_global_options "$help")")$'\n\n'
  local sub
  while IFS= read -r sub; do
    [[ -n "$sub" ]] && walk "$@" "$sub"
  done < <(subcommands_in "$help")
}

ROOT=$(help_of)
while IFS= read -r top; do
  [[ -n "$top" ]] && walk "$top"
done < <(subcommands_in "$ROOT")

cat <<'EOF'
# Command reference

Every page of `hipc --help`, rendered by `scripts/docs-reference.sh` from the built binary.
Do not edit this file: change the help text in `crates/hippius-cli/src/cli`, then run
`scripts/docs-reference.sh target/debug/hipc > docs/commands.md`. A test fails while the
two differ.

The global options are listed once, under [`hipc`](#hipc); every command takes them. The
same tree, with each command's effect, confirmation, guards, and flags as JSON, is
`hipc schema`.

## Contents

- [`hipc`](#hipc)
EOF
printf '%s\n' "$TOC"
section '##' 'hipc' "$ROOT"
# The last section ends the file with one line break, where the others end with a blank line.
printf '%s' "${BODY%$'\n'}"
