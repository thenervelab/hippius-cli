#!/usr/bin/env bash
# Prints Formula/hipc.rb for the thenervelab/homebrew-tap repository.
#
# The formula is named `hipc`, as the command it installs is, so `brew install
# thenervelab/tap/hipc` installs it. It replaces the tap's earlier `hipc` formula, which
# installed the deprecated IPFS-era CLI of that name, so `brew upgrade` moves its users onto
# this one; the caveats say so. The description is written here, not read from Cargo.toml,
# so that it passes Homebrew's audit (at most 80 characters, no leading formula name).
#
# Usage: scripts/brew-formula.sh <version> <path to SHA256SUMS>
#
# The formula installs the release tarballs from the releases of thenervelab/hippius-cli: one per
# platform, each with the sha256 its line in SHA256SUMS gives. It reads no network and
# writes no file.
set -euo pipefail

# The repository whose releases hold the tarballs.
REPO='thenervelab/hippius-cli'

die() {
  echo "brew-formula: error: $1" >&2
  exit 1
}

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <version> <path to SHA256SUMS>" >&2
  exit 2
fi
VERSION="$1"
SUMS="$2"
[[ "$VERSION" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]] || die "not a version: $VERSION (expected X.Y.Z)"
[[ -r "$SUMS" ]] || die "cannot read $SUMS"

BASE="https://github.com/$REPO/releases/download/v$VERSION"

# Prints the url and sha256 lines of one target, indented for a nested block.
asset() {
  local target="$1" sum
  sum=$(awk -v name="hipc-$target.tar.gz" '$2 == name || $2 == "*" name { print $1 }' "$SUMS")
  [[ "$sum" =~ ^[0-9a-f]{64}$ ]] ||
    die "$SUMS has no single well-formed line for hipc-$target.tar.gz"
  echo "      url \"$BASE/hipc-$target.tar.gz\""
  echo "      sha256 \"$sum\""
}

# Every value is computed before the first line is printed, so a failure prints nothing
# that could be mistaken for a formula. The explicit exits do not lean on how `set -e`
# treats a failed command substitution, which differs between bash versions.
MAC_ARM=$(asset aarch64-apple-darwin) || exit 1
MAC_INTEL=$(asset x86_64-apple-darwin) || exit 1
LINUX_ARM=$(asset aarch64-unknown-linux-musl) || exit 1
LINUX_INTEL=$(asset x86_64-unknown-linux-musl) || exit 1

# No `depends_on arch:`. Homebrew's ArchRequirement takes one architecture, so
# `depends_on arch: [:arm64, :x86_64]` would demand arm64 alone, and Homebrew itself runs
# only on 64-bit arm and Intel, which on_arm and on_intel already cover.

cat <<EOF
# Generated by scripts/brew-formula.sh in thenervelab/hippius-cli. Do not edit.
class Hipc < Formula
  desc "Control plane for the Hippius console, for agents and people"
  homepage "https://github.com/$REPO"
  version "$VERSION"
  license any_of: ["MIT", "Apache-2.0"]

  on_macos do
    on_arm do
$MAC_ARM
    end
    on_intel do
$MAC_INTEL
    end
  end

  on_linux do
    on_arm do
$LINUX_ARM
    end
    on_intel do
$LINUX_INTEL
    end
  end

  def install
    bin.install "hipc"
  end

  def caveats
    "This hipc is the Hippius console CLI; the IPFS-era hipc commands are gone. Run \`hipc --help\` to start."
  end

  test do
    assert_equal "hipc #{version}", shell_output("#{bin}/hipc --version").strip
  end
end
EOF
